/**
 * Working-tree Git operations for the project commits tab: read the current
 * workspace state, commit manually, pull (fast-forward only) and push the
 * checked-out branch. All write operations on one workspace are serialized so
 * they also cannot interleave with each other.
 */
import { promises as fsp } from 'node:fs'
import path from 'node:path'
import { withKeyLock } from '../shared/atomic.js'
import { apiError } from '../errors.js'
import { messages } from '../messages/index.js'
import { ensureReviewExclude } from '../domain/reviews.js'
import { ACTIVE_TASK_STATUSES, readTasksForApi } from '../storage/tasks.js'
import {
  assertGitRoot,
  commitProject,
  projectWorkspaceChanges,
  pullProjectBranch,
  pushProjectBranch,
  runGit,
  upstreamState,
} from '../integrations/git.js'
import { requireProject } from './projects.js'

const MANUAL_COMMIT_MESSAGE_LIMIT = 2000

function validateManualCommitMessage(value) {
  if (typeof value !== 'string') {
    throw apiError(400, 'bad-manual-commit-message', messages.badManualCommitMessage)
  }
  const text = value.trim()
  if (text.length === 0 || text.length > MANUAL_COMMIT_MESSAGE_LIMIT) {
    throw apiError(400, 'bad-manual-commit-message', messages.badManualCommitMessage)
  }
  return text
}

async function assertBranchCheckedOut(root) {
  const result = await runGit(root, ['symbolic-ref', '--short', '-q', 'HEAD'])
  const branch = result.code === 0 ? result.stdout.trim() : ''
  if (branch.length === 0) {
    throw apiError(400, 'detached-head', messages.projectDetached)
  }
}

/** Active AI commit task in this workspace blocks manual commit and pull. */
async function assertNoActiveCommitTask(workspaceId) {
  const tasks = await readTasksForApi()
  const active = tasks.find(function (task) {
    if (task.workspaceId !== workspaceId || task.kind !== 'commit') return false
    return ACTIVE_TASK_STATUSES.includes(task.status)
  })
  if (active !== undefined) {
    throw apiError(409, 'project-task-active', messages.projectCommitTaskActive)
  }
}

/** Best-effort "same directory" check: resolve symlinks, fall back to path.resolve. */
async function sameDirectory(left, right) {
  if (typeof left !== 'string' || left.length === 0) return false
  if (path.resolve(left) === path.resolve(right)) return true
  try {
    return await fsp.realpath(left) === path.resolve(right)
  } catch {
    return false
  }
}

/**
 * A requirement execution running in the project main workspace (its task cwd is
 * the project root) blocks manual commit / pull, because the agent may still be
 * writing files. Requirement executions inside their own worktree do not block
 * the main workspace. Legacy records: `worktreePath` set means worktree
 * execution; a record with neither path is treated conservatively as main.
 */
async function assertProjectWorkspaceIdle(workspaceId, root) {
  const tasks = await readTasksForApi()
  const candidates = tasks.filter(function (task) {
    if (task.workspaceId !== workspaceId || task.kind !== 'requirement') return false
    return ACTIVE_TASK_STATUSES.includes(task.status)
  })
  for (const task of candidates) {
    const worktreePath = typeof task.worktreePath === 'string' ? task.worktreePath : ''
    if (worktreePath.length > 0) continue
    const projectPath = typeof task.projectPath === 'string' ? task.projectPath : ''
    if (projectPath.length === 0 || await sameDirectory(projectPath, root)) {
      throw apiError(409, 'requirement-running', messages.projectRequirementRunning)
    }
  }
}

/** Current uncommitted changes of the project working tree for the commits tab. */
export async function readProjectWorkspaceState(ctx, workspaceId) {
  const current = await requireProject(ctx, workspaceId)
  return projectWorkspaceChanges(current.canonicalPath)
}

/**
 * Commit every current change (`git add -A`) with a user-supplied message.
 * Validation order is part of the HTTP contract: message, Git project, detached
 * HEAD, active AI commit task, requirement running in the main workspace.
 */
export function manualCommitProject(ctx, workspaceId, messageInput) {
  const message = validateManualCommitMessage(messageInput)
  return withKeyLock('project-git:' + workspaceId, async function () {
    const current = await requireProject(ctx, workspaceId)
    const root = current.canonicalPath
    await assertGitRoot(root)
    await assertBranchCheckedOut(root)
    await assertNoActiveCommitTask(workspaceId)
    await assertProjectWorkspaceIdle(workspaceId, root)
    // Review artifacts are generated by this plugin and must never end up in a
    // project commit; the AI commit flow guards them the same way.
    await ensureReviewExclude(root)
    const commit = await commitProject(root, message)
    return { commit: { hash: commit.hash, short: commit.short, subject: commit.subject } }
  })
}

/**
 * Fast-forward-only pull. The pre-check keeps the contract order (detached
 * HEAD / missing upstream before task guards); the integration re-validates the
 * Git state when it runs the pull.
 */
export function pullProject(ctx, workspaceId) {
  return withKeyLock('project-git:' + workspaceId, async function () {
    const current = await requireProject(ctx, workspaceId)
    const root = current.canonicalPath
    await assertGitRoot(root)
    await assertBranchCheckedOut(root)
    if (await upstreamState(root) === null) {
      throw apiError(400, 'pull-no-upstream', messages.projectPullNoUpstream)
    }
    await assertNoActiveCommitTask(workspaceId)
    await assertProjectWorkspaceIdle(workspaceId, root)
    return pullProjectBranch(root)
  })
}

/** Push the checked-out branch, establishing upstream with `-u` when missing. */
export function pushProject(ctx, workspaceId) {
  return withKeyLock('project-git:' + workspaceId, async function () {
    const current = await requireProject(ctx, workspaceId)
    return pushProjectBranch(current.canonicalPath)
  })
}
