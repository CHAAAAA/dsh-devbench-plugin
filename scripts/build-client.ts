/**
 * Build the browser half of the plugin into `dist/client.js`.
 *
 * The DSH client-modules host half reads the prebuilt bundle from the path in
 * `exports["./client"]`; it never compiles TypeScript or source modules itself.
 * The bundle registers itself on `window.__ModuleLoader__` with the package
 * name injected through esbuild `define`, so the module id can never drift from
 * `package.json.name`.
 */
import fs from 'node:fs'
import { createHash } from 'node:crypto'
import { build } from 'esbuild'

const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'))
const outfile = 'dist/client.js'

const result = await build({
  entryPoints: ['src/client/entry.ts'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome100'],
  outfile,
  write: false,
  external: ['react'],
  define: { __PLUGIN_ID__: JSON.stringify(pkg.name) },
  banner: {
    js: '/* ' + pkg.name + '@' + pkg.version +
      ' client bundle — generated by scripts/build-client.ts; edit src/client instead. */',
  },
  legalComments: 'none',
  logLevel: 'warning',
})

const code = result.outputFiles[0].text

fs.mkdirSync('dist', { recursive: true })
fs.writeFileSync(outfile, code)
const bytes = fs.statSync(outfile).size
const sha256 = createHash('sha256').update(code).digest('hex').slice(0, 16)
console.log('built ' + outfile + ' bytes=' + bytes + ' sha256=' + sha256)
